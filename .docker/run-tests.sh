#!/usr/bin/env bash
#
# Run the test suite against every supported PHP version using Docker.
#
# Usage: .docker/run-tests.sh [PHP_VERSION ...]   e.g. .docker/run-tests.sh 5.3 8.5
#
# Dependencies are resolved on the host with Composer, using a platform
# override for each target PHP version. PHPUnit itself then runs inside a
# container providing that PHP version. Each version gets its own working
# copy below build/test-php-<version>/, so the project's own vendor/ is left
# untouched.
#
# Requirements on the host: bash, docker, composer, rsync.

set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ALL_VERSIONS="5.3 5.4 5.5 5.6 7.0 7.1 7.2 7.3 7.4 8.0 8.1 8.2 8.3 8.4 8.5"
VERSIONS="${*:-$ALL_VERSIONS}"

# Images are pulled through Google's Docker Hub mirror by default to avoid
# Docker Hub's rate limit for anonymous pulls. Use DOCKER_REGISTRY=docker.io
# to pull from Docker Hub directly.
DOCKER_REGISTRY="${DOCKER_REGISTRY:-mirror.gcr.io}"

# The official php images for 5.3 and 5.4 use a manifest format current
# Docker versions can no longer pull, hence the devilbox images.
image_for() {
    case "$1" in
        5.3|5.4) echo "$DOCKER_REGISTRY/devilbox/php-fpm-$1" ;;
        *)       echo "$DOCKER_REGISTRY/library/php:$1-cli" ;;
    esac
}

# Autoloaders generated by Composer >= 2.3 refuse to run on PHP < 5.6, so
# those versions need Composer 2.2 LTS.
COMPOSER_LTS="$PROJECT_DIR/build/composer-2.2.phar"
composer_for() {
    case "$1" in
        5.3|5.4|5.5)
            if [ ! -f "$COMPOSER_LTS" ]; then
                mkdir -p "$(dirname "$COMPOSER_LTS")"
                curl -sSfL -o "$COMPOSER_LTS" https://getcomposer.org/download/latest-2.2.x/composer.phar
            fi
            echo "php -d error_reporting=E_ALL&~E_DEPRECATED $COMPOSER_LTS"
            ;;
        *)  echo "composer" ;;
    esac
}

failed=""

for version in $VERSIONS; do
    echo "=== PHP $version ==="
    workdir="$PROJECT_DIR/build/test-php-$version"
    mkdir -p "$workdir"
    rsync -a --delete \
        --exclude '/.git' --exclude '/.idea' --exclude '/.tools' \
        --exclude '/build' --exclude '/vendor' --exclude '/composer.lock' \
        --exclude '/.phpunit.cache' --exclude '/.phpunit.result.cache' \
        "$PROJECT_DIR/" "$workdir/"

    (
        cd "$workdir"
        composer="$(composer_for "$version")"
        $composer config platform.php "$version.99"
        # PHPUnit versions for old PHP releases have published security
        # advisories; Composer >= 2.9 refuses to install them by default.
        # They are dev-only dependencies, so allow them.
        COMPOSER_NO_SECURITY_BLOCKING=1 $composer update --no-interaction --no-progress --quiet
    )

    # date.timezone is set like setup-php does in CI: PHP 5.x throws on
    # "new DateTime()" if no timezone is configured.
    if docker run --rm --entrypoint php -v "$workdir:/app" -w /app "$(image_for "$version")" \
        -r 'echo "PHP ", PHP_VERSION, PHP_EOL; passthru("php -d date.timezone=UTC vendor/phpunit/phpunit/phpunit", $code); passthru("php -d date.timezone=UTC bin/ddate \"%{%A, %B %d,%} %Y YOLD\" 29022012", $c2); echo PHP_EOL; exit($code || $c2 ? 1 : 0);'
    then
        echo "=== PHP $version: OK ==="
    else
        echo "=== PHP $version: FAILED ==="
        failed="$failed $version"
    fi
done

if [ -n "$failed" ]; then
    echo "Failed PHP versions:$failed"
    exit 1
fi
echo "All PHP versions passed: $VERSIONS"
